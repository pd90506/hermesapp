// Writes src/renderer/theme/themes/themes.css from Packages/fixtures/appearance-themes.json,
// which HermesKit generates (AppearanceFixtureTests.swift), so this app draws the Mac and
// iOS apps' very colours. Run after the fixture changes:
//   node Apps/Desktop/electron/scripts/export-themes.mjs
// tests/appearance/themes-css.test.ts fails while the stylesheet is out of date.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const fixturePath = join(import.meta.dirname, '../../../../Packages/fixtures/appearance-themes.json')
export const stylesheetPath = join(import.meta.dirname, '../src/renderer/theme/themes/themes.css')

/** Token name → where its colour is in a fixture theme. */
const surfaceTokens = [
  ['--accent', (theme) => theme.accent],
  ['--surface-frame', (theme) => theme.surfaces.frame],
  ['--surface-chrome', (theme) => theme.surfaces.chrome],
  ['--surface-chat', (theme) => theme.surfaces.chat],
  ['--composer-fill', (theme) => theme.surfaces.composer],
  ['--selection-fill', (theme) => theme.surfaces.selection],
  ['--user-bubble', (theme) => theme.surfaces.userBubble],
]

/** The Markdown colour tokens (B's renderer reads them), by HermesKit element. */
export const markdownTokens = {
  heading: '--md-heading',
  bold: '--md-bold',
  link: '--md-link',
  inlineCode: '--md-inline-code',
  inlineCodeBackground: '--md-inline-code-bg',
  codeBlockBackground: '--md-code-block-bg',
  quoteBar: '--md-quote-bar',
  quoteText: '--md-quote-text',
  quoteBackground: '--md-quote-bg',
  tableHeaderBackground: '--md-table-header-bg',
  tableHeaderText: '--md-table-header-text',
  tableBorder: '--md-table-border',
  tableStripe: '--md-table-stripe',
}

/** The theme's declarations in one mode. System (plain) keeps the platform's own surfaces. */
function declarations(theme, mode) {
  const lines = []
  if (theme.theme !== 'plain') {
    for (const [token, colour] of surfaceTokens) {
      const pair = colour(theme)
      if (pair) lines.push(`${token}: ${pair[mode]};`)
    }
  }
  for (const [element, token] of Object.entries(markdownTokens)) lines.push(`${token}: ${theme.markdown[element][mode]};`)
  return lines
}

function block(selector, lines, indent = '') {
  return [`${indent}${selector} {`, ...lines.map((line) => `${indent}  ${line}`), `${indent}}`].join('\n')
}

export function renderThemes(fixture) {
  const parts = [
    '/*',
    ' * GENERATED by scripts/export-themes.mjs from Packages/fixtures/appearance-themes.json',
    " * (HermesKit's ColorTheme and MarkdownColors). Do not edit; change HermesKit and re-export.",
    ' *',
    ' * <html data-theme> picks the theme (Settings > Appearance > Theme); light or dark follows',
    ' * prefers-color-scheme, which the main process sets from the Appearance mode',
    ' * (nativeTheme.themeSource). System (data-theme="plain", and before a theme applies)',
    " * keeps the platform's own surfaces and accent (tokens.css, platform.css).",
    ' */',
    '/* M */',
  ]
  for (const theme of fixture.themes) {
    const selector = theme.theme === 'plain' ? ":root,\n:root[data-theme='plain']" : `:root[data-theme='${theme.theme}']`
    parts.push('', `/* ${theme.theme} */`, block(selector, declarations(theme, 'light')))
    parts.push('@media (prefers-color-scheme: dark) {', block(selector.replace(/\n/g, '\n  '), declarations(theme, 'dark'), '  '), '}')
  }
  // The Appearance pane's swatches: each theme's accent; System's is the system's.
  const swatch = (theme) => `[data-theme-swatch='${theme.theme}']`
  parts.push('', '/* Theme swatches (Settings > Appearance > Theme). */')
  for (const theme of fixture.themes) {
    const colour = theme.accent ? theme.accent.light : 'var(--system-accent, #0067c0)'
    parts.push(`${swatch(theme)} { --swatch-color: ${colour}; }`)
  }
  parts.push('@media (prefers-color-scheme: dark) {')
  for (const theme of fixture.themes) {
    if (theme.accent) parts.push(`  ${swatch(theme)} { --swatch-color: ${theme.accent.dark}; }`)
  }
  parts.push('}')
  return `${parts.join('\n')}\n`
}

export function exportedStylesheet() {
  return renderThemes(JSON.parse(readFileSync(fixturePath, 'utf8')))
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) {
  writeFileSync(stylesheetPath, exportedStylesheet())
  console.log(`wrote ${stylesheetPath}`)
}
