#!/usr/bin/env node
// Generates src/protocol/contract.generated.ts from Hermes's OpenRPC contract,
// `apps/shared/src/gateway-contract.openrpc.json` in a Hermes checkout (MIT, Nous Research).
//
//   node scripts/gen-contract.mjs <path to gateway-contract.openrpc.json> [--source "<label>"]
//
// The label (a Hermes version or commit) goes in the file's header. Every field the
// contract does not require is optional, as HermesKit decodes them: older and newer
// gateways still type-check against what is actually read.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const args = process.argv.slice(2)
const input = args.find((a) => !a.startsWith('--'))
const sourceAt = args.indexOf('--source')
const source = sourceAt >= 0 ? args[sourceAt + 1] : undefined
if (!input) {
  console.error('usage: gen-contract.mjs <gateway-contract.openrpc.json> [--source "<label>"]')
  process.exit(2)
}
const contract = JSON.parse(readFileSync(input, 'utf8'))
const schemas = contract.components?.schemas ?? {}

const identifier = (name) => name.replace(/[^A-Za-z0-9_]/g, '_')
const refName = (ref) => identifier(ref.replace('#/components/schemas/', ''))
const key = (name) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name))
const doc = (text, indent = '') => {
  if (!text) return ''
  const body = String(text).replace(/\*\//g, '*\\/').trim().split('\n')
  return body.length === 1
    ? `${indent}/** ${body[0]} */\n`
    : `${indent}/**\n${body.map((l) => `${indent} * ${l}`.trimEnd()).join('\n')}\n${indent} */\n`
}

function type(schema, indent) {
  if (schema === true || schema === undefined || schema === null) return 'unknown'
  if (schema === false) return 'never'
  if (schema.$ref) return refName(schema.$ref)
  if ('const' in schema) return JSON.stringify(schema.const)
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ')
  if (schema.anyOf || schema.oneOf) {
    const parts = [...new Set((schema.anyOf ?? schema.oneOf).map((s) => type(s, indent)))]
    return parts.length === 1 ? parts[0] : parts.map((p) => (p.includes('=>') ? `(${p})` : p)).join(' | ')
  }
  if (schema.allOf) return schema.allOf.map((s) => type(s, indent)).join(' & ')
  if (Array.isArray(schema.type)) return schema.type.map((t) => type({ ...schema, type: t }, indent)).join(' | ')
  switch (schema.type) {
    case 'string': return 'string'
    case 'integer':
    case 'number': return 'number'
    case 'boolean': return 'boolean'
    case 'null': return 'null'
    case 'array': {
      if (Array.isArray(schema.prefixItems)) return `[${schema.prefixItems.map((s) => type(s, indent)).join(', ')}]`
      const item = type(schema.items, indent)
      return /[ |&]/.test(item) ? `Array<${item}>` : `${item}[]`
    }
    case 'object':
    case undefined: {
      if (schema.properties) return objectBody(schema, indent)
      const extra = schema.additionalProperties
      if (extra && extra !== true) return `Record<string, ${type(extra, indent)}>`
      return schema.type === 'object' ? 'Record<string, unknown>' : 'unknown'
    }
    default: return 'unknown'
  }
}

function objectBody(schema, indent) {
  const required = new Set(schema.required ?? [])
  const inner = indent + '  '
  const lines = Object.entries(schema.properties).map(([name, prop]) =>
    `${doc(prop.description, inner)}${inner}${key(name)}${required.has(name) ? '' : '?'}: ${type(prop, inner)}`)
  const extra = schema.additionalProperties
  if (extra && extra !== true && extra !== false) lines.push(`${inner}[key: string]: unknown`)
  return `{\n${lines.join('\n')}\n${indent}}`
}

let out = `// GENERATED by Packages/hermes-core/scripts/gen-contract.mjs - do not edit.
// From Hermes's gateway contract (apps/shared/src/gateway-contract.openrpc.json,
// Copyright (c) 2025 Nous Research, MIT License)${source ? `, ${source}` : ''}.
// Regenerate: node Packages/hermes-core/scripts/gen-contract.mjs <contract> --source "<label>"
/* eslint-disable */

`
for (const [name, schema] of Object.entries(schemas).sort(([a], [b]) => a.localeCompare(b))) {
  out += doc(schema.description)
  const body = type(schema, '')
  out += schema.properties && !schema.anyOf && !schema.allOf
    ? `export interface ${identifier(name)} ${body}\n`
    : `export type ${identifier(name)} = ${body}\n`
}

const methodMap = (title, list, withResult) => {
  let text = `\n/** ${title} */\nexport interface ${title} {\n`
  for (const m of [...list].sort((a, b) => a.name.localeCompare(b.name))) {
    const params = m.params?.[0]?.schema ? type(m.params[0].schema, '    ') : 'undefined'
    text += doc(m.summary, '  ')
    text += withResult
      ? `  ${JSON.stringify(m.name)}: { params: ${params}; result: ${m.result ? type(m.result.schema, '    ') : 'unknown'} }\n`
      : `  ${JSON.stringify(m.name)}: ${params}\n`
  }
  return text + '}\n'
}
out += methodMap('GatewayMethods', contract.methods ?? [], true)
out += methodMap('GatewayServerRequests', contract['x-server-requests'] ?? [], true)
out += methodMap('GatewayEventPayloads', contract['x-notifications'] ?? [], false)
out += `
export type GatewayMethodName = keyof GatewayMethods
export type GatewayParams<M extends GatewayMethodName> = GatewayMethods[M]['params']
export type GatewayResult<M extends GatewayMethodName> = GatewayMethods[M]['result']
`

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'protocol', 'contract.generated.ts')
writeFileSync(target, out)
console.log(`wrote ${target}: ${Object.keys(schemas).length} schemas, ${(contract.methods ?? []).length} methods`)
